@dataclass
class Screen:
    """Everything the one screen shows, computed once."""

    dataset: DatasetReport
    result: ThresholdResult
    impact: ImpactTable
    metrics: Any
    failures: list[Any]
    question: str
    question_label: str


def build_records() -> tuple[list[DecisionRecord], list[DecisionRecord]]:
    """The version in production, and the candidate that has to be judged against it.

    The production half is `jeval demo`'s own log at the same seed, so the numbers on the screen can
    be checked against the committed report in this repository. The candidate is the same four
    questions generated by a degraded model: overconfident on the question the cost matrix fires on,
    which is the change the drift check exists to catch.
    """
    serving = list(demo_dataset(seed=11, scale=0.5).records)
    degraded = (
        SynthSpec(
            n=310,
            mode="overconfident",
            exponent=0.35,
            question_key="department",
            model="jev-1.14.0",
            start=NEWER_START,
            seed=21,
            languages=("ko", "en"),
            tiers=("free", "pro"),
            label_fraction=0.86,
        ),
        SynthSpec(
            n=270,
            mode="inflated",
            inflation=1.3,
            question_key="intent",
            classes=("refund_request", "check_balance", "other"),
            model="jev-1.14.0",
            start=NEWER_START,
            seed=22,
            languages=("ko", "en"),
            label_fraction=0.9,
        ),
        SynthSpec(
            n=215,
            mode="calibrated",
            question_key="is_urgent",
            question_type="noul",
            model="jev-1.14.0",
            start=NEWER_START,
            seed=23,
            languages=("ko", "en"),
            label_fraction=0.88,
        ),
        SynthSpec(
            n=110,
            mode="inflated",
            question_key="satisfaction",
            question_type="score",
            score_bias=0.18,
            model="jev-1.14.0",
            start=NEWER_START,
            seed=24,
            languages=("ko", "en"),
            label_fraction=0.8,
        ),
    )
    candidate = [record for spec in degraded for record in generate(spec)]
    return serving, candidate


def analyse(
    serving: Sequence[DecisionRecord], candidate: Sequence[DecisionRecord], costs_path: Path
) -> Screen:
    """Run the analysis the report runs, and keep the pieces one screen needs.

    The screen measures the version in production: a rollout decision is "here is what is live, here
    is what is proposed", and mixing the candidate into the reliability numbers would hide which of
    the two is miscalibrated. The candidate appears once, as the drift check's failure.
    """
    records = list(serving)
    dataset = evaluate(records, n_bins=10, alpha=0.05, n_boot=200, by=("lang", "tier"))
    actions, _note = resolve_cost_actions(costs_path, costs_path.parent)
    thresholds, impacts = sweep_actions(
        actions,
        records,
        n_boot=200,
        alpha=0.05,
        monthly_volume=MONTHLY_VOLUME,
        currency=CURRENCY,
        current_threshold=CURRENT_THRESHOLD,
    )
    result = next((item for item in thresholds if item.curve), None)
    assert result is not None, "the demo cost matrix must produce a sweep"
    question = next(
        (item for item in dataset.questions if item.question_key == result.question), None
    )
    metrics = question.metrics if question is not None else dataset.overall
    drift = _drift_view([*records, *candidate])
    failures = list(run_checks(drift, parse_fail_on((FAIL_ON,)))) if drift is not None else []
    return Screen(
        dataset=dataset,
        result=result,
        impact=impacts[result.action],
        metrics=metrics,
        failures=failures,
        question=result.question,
        question_label=result.action,
    )


def _drift_view(records: Sequence[DecisionRecord], *, min_slice: int = 30) -> Any:
    """Compare model versions when the log holds more than one."""
    if len({record.model for record in records}) < 2:
        return None
    from jeval import drift as drift_engine

    return drift_engine.compare(records, min_slice=min_slice, alpha=0.05, n_boot=200)


