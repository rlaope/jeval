# Drawn here rather than taken from `jeval.report.charts`, because this chart has to do something the
# report's does not: put both thresholds on one axis, label them where they stand, and show the
# confidence distribution underneath, so the reader can see what moves when the line moves.
# Colours come from CSS classes rather than attributes, so the chart follows the colour scheme.
def _threshold_line(
    x: float,
    *,
    y0: float,
    y1: float,
    label: str,
    anchor: str,
    line_cls: str,
    label_cls: str,
    dash: str = "",
) -> str:
    """A vertical line where a threshold sits, labelled where it sits.

    Both lines on this chart are labelled in words as well as drawn in different colours and dash
    patterns: a reader who cannot tell the colours apart still gets the whole argument.
    """
    return "".join(
        (
            S.line(x, y0, x, y1, dash=dash, cls=line_cls),
            S.text(
                x + (-10 if anchor == "end" else 10),
                LABEL_Y,
                label,
                anchor=anchor,
                size=13.5,
                weight=700,
                cls=label_cls,
                halo=True,
            ),
        )
    )


def _chart(screen: Screen) -> str:
    points = [point for point in screen.result.curve if point.expected_cost == point.expected_cost]
    assert points, "the sweep must produce points"
    costs = [point.expected_cost for point in points]
    lo, hi = min(costs), max(costs)
    pad = max(1e-9, (hi - lo) * 0.18)
    y_lo, y_hi = max(0.0, lo - pad), hi + pad

    x0, x1 = PLOT_LEFT, CHART_W - PLOT_RIGHT
    y_top = PLOT_TOP
    y_bottom = CHART_H - PLOT_BOTTOM
    strip_top = y_bottom + STRIP_GAP
    strip_bottom = strip_top + STRIP_H

    def px(threshold: float) -> float:
        return x0 + threshold * (x1 - x0)

    def py(cost: float) -> float:
        return y_bottom - (cost - y_lo) / max(1e-12, y_hi - y_lo) * (y_bottom - y_top)

    current = screen.impact.current_threshold or CURRENT_THRESHOLD
    belongs = screen.result.threshold
    per_case = screen.result.expected_cost_per_case
    at_current = screen.result.point_at(current)
    currency = screen.impact.currency
    # The sweep is flat until it has a case it could move: below the lowest confidence the model
    # handles alone, raising the line changes nothing. Unannotated, that plateau reads as a
    # rendering fault -- its step lands exactly on the "in use" line -- so the chart says what it is.
    plateau = points[0].expected_cost
    plateau_end = max(
        (point.threshold for point in points if abs(point.expected_cost - plateau) < 1e-9),
        default=0.0,
    )

    parts = [
        S.svg_open(
            CHART_W,
            CHART_H,
            title=(
                "Expected cost per case against the threshold, with the line in use and the line "
                "the cost minimum points at"
            ),
            desc=(
                f"Cost per case is lowest at threshold {S.fmt(belongs)}, where it is "
                f"{S.money(per_case)}, and higher at the {S.fmt(current)} currently in use. The "
                "bars below the curve show how many decisions sit in each confidence range."
            ),
            cls="hero",
        )
    ]

    # The bootstrap interval on the threshold, drawn and not only printed: a point estimate quoted
    # over a wide interval is the easiest thing on this page to over-read.
    ci_low, ci_high = screen.result.ci_low, screen.result.ci_high
    if ci_high > ci_low:
        parts.append(
            S.rect(
                px(ci_low),
                y_top,
                px(ci_high) - px(ci_low),
                strip_bottom - y_top,
                cls="ci-band",
                extra=' stroke="none"',
            )
        )

    # Few gridlines: horizontal only, at round costs. The x axis gets tick marks, not a lattice.
    for value in S.nice_ticks(y_lo, y_hi, target=4):
        y = py(value)
        parts.append(S.line(x0, y, x1, y, cls="grid"))
        parts.append(
            S.text(x0 - 10, y + 4.5, S.money(value), anchor="end", size=13, mono=True, cls="tick")
        )
    for value in (0.0, 0.25, 0.5, 0.75, 1.0):
        x = px(value)
        parts.append(S.line(x, strip_bottom, x, strip_bottom + 6, cls="axis"))
        parts.append(
            S.text(x, X_TICK_Y, S.fmt(value), anchor="middle", size=13, mono=True, cls="tick")
        )
    parts.append(S.line(x0, y_bottom, x1, y_bottom, cls="axis"))
    parts.append(S.line(x0, strip_bottom, x1, strip_bottom, cls="axis"))
    parts.append(
        S.text(
            (x0 + x1) / 2.0,
            X_TITLE_Y,
            "threshold: how sure the model has to be before it answers alone",
            anchor="middle",
            size=13,
            cls="label",
        )
    )
    parts.append(
        S.text(
            Y_TITLE_X,
            (y_top + y_bottom) / 2.0,
            f"cost per case ({currency})",
            anchor="middle",
            size=13,
            cls="label",
            rotate=-90,
            rotate_at=(Y_TITLE_X, (y_top + y_bottom) / 2.0),
        )
    )

    # The distribution under the curve: how many decisions sit in each confidence band.
    buckets = list(screen.metrics.confidence_buckets)
    if buckets:
        peak = max(count for _lo, _hi, count in buckets) or 1
        for band_lo, band_hi, count in buckets:
            left = px(band_lo) + 1.0
            width = max(1.0, px(band_hi) - px(band_lo) - 2.0)
            height = max(1.0, (count / peak) * STRIP_H)
            parts.append(
                S.rect(
                    left,
                    strip_bottom - height,
                    width,
                    height,
                    cls="dist",
                    extra=' stroke="none"',
                )
            )
        # Every occupied band carries its count: with one band holding most of the decisions, the
        # other bars are a few pixels tall, and the number is what makes them readable.
        for band_lo, band_hi, count in buckets:
            if count:
                height = (count / peak) * STRIP_H
                parts.append(
                    S.text(
                        (px(band_lo) + px(band_hi)) / 2.0,
                        strip_bottom - height - 4,
                        f"{count:,}",
                        anchor="middle",
                        size=13,
                        mono=True,
                        cls="tick",
                    )
                )
        parts.append(
            S.text(
                x0,
                strip_top - 9,
                f"{screen.metrics.n:,} labeled decisions in these bands",
                size=13,
                cls="label",
            )
        )
        # The strip has its own unit, so it gets its own axis label; without one, bar heights read
        # as cost levels.
        parts.append(
            S.text(x0 - 10, strip_top + 12, "decisions", anchor="end", size=11, cls="tick")
        )

    parts.append(
        S.polyline(
            [(px(point.threshold), py(point.expected_cost)) for point in points],
            cls="curve",
            smooth=True,
        )
    )
    # Say why the left half of the curve is flat, using the threshold the plateau actually ends at.
    if plateau_end >= 0.2:
        parts.append(
            S.text(
                x0 + 10,
                py(plateau) + 18,
                f"flat to {S.fmt(plateau_end)}: every case the model would handle alone already "
                "sits above the line",
                size=12.5,
                cls="label",
                halo=True,
            )
        )
    # Direct labels on the two points that matter, so the reader never has to trace to an axis.
    if at_current is not None:
        y_now = py(at_current.expected_cost)
        parts.append(S.dot(px(current), y_now, 4.0, cls="inuse-dot", extra=' stroke="none"'))
        parts.append(
            S.text(
                px(current) - 12,
                y_now - 10,
                f"{currency} {at_current.expected_cost:,.2f} per case",
                anchor="end",
                size=13,
                mono=True,
                cls="tick",
                halo=True,
            )
        )
    parts.append(
        S.dot(
            px(belongs),
            py(per_case),
            4.5,
            cls="min-dot",
            tooltip=f"cost minimum at {S.fmt(belongs)}",
            extra=' stroke="none"',
        )
    )
    parts.append(
        S.text(
            px(belongs) + 10,
            py(per_case) + 18,
            f"{currency} {per_case:,.2f} per case",
            size=13,
            mono=True,
            cls="tick",
            halo=True,
        )
    )
    parts.append(
        _threshold_line(
            px(current),
            y0=y_top,
            y1=strip_bottom,
            label=f"in use {S.fmt(current)}",
            anchor="end",
            line_cls="inuse-line",
            label_cls="inuse-label",
            dash="5 4",
        )
    )
    parts.append(
        _threshold_line(
            px(belongs),
            y0=y_top,
            y1=strip_bottom,
            label=f"where it belongs {S.fmt(belongs)}",
            anchor="start",
            line_cls="belongs-line",
            label_cls="belongs-label",
        )
    )
    if ci_high > ci_low:
        parts.append(
            S.text(
                x1,
                LABEL_Y + 16,
                f"shaded: 95% interval {S.fmt(ci_low)}–{S.fmt(ci_high)}",
                anchor="end",
                size=13,
                mono=True,
                cls="tick",
                halo=True,
            )
        )
    parts.append(S.svg_close())
    return "".join(parts)


