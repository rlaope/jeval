"""Build the one-screen dashboard used for the walkthrough recording.

This is not a jeval command and not a product surface: the product writes one report, and a
dashboard is explicitly out of scope. This is a *presentation* of the same analysis, computed by the
same library, arranged so that one screen makes one argument -- the line in use is in the wrong
place, here is where it belongs, here is what moving it buys.

    uv run python examples/make-demo-dashboard.py examples/demo-dashboard.html

One file, no server, no network, no chart library, no JavaScript. Every figure is computed by the
library the report uses (``evaluate``, ``sweep_actions``, ``build_impact``), and nothing on the page
is typed in by hand, which is what makes it safe to put on screen.

The synthetic log is two model versions of the same four questions. The older version is roughly
honest on the question the cost matrix fires on; the newer one is degraded, which is the change the
drift check exists to catch.
"""

